// Build sidecars/agy-lens/web/views/share-font.js from a Fusion Pixel 12px BDF (dev-only tool).
//
//   node scripts/share-art/build-font.mjs <fusion-pixel-12px-proportional-zh_hans.bdf> <latin.bdf>
//
// Keeps printable ASCII, GB2312 level-1 hanzi (3755), CJK punctuation and every character used
// by web/i18n.js, so nicknames in common Chinese and all card labels render as true pixels.
// Font: Fusion Pixel Font, (c) 2022 TakWolf, SIL Open Font License 1.1 (see share-art/fonts/OFL.txt).

import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const [zhPath, latinPath] = process.argv.slice(2);
if (!zhPath) {
  console.error('usage: build-font.mjs <zh_hans.bdf> [latin.bdf]');
  process.exit(1);
}

function parseBdf(path) {
  const glyphs = new Map();
  const meta = {};
  const lines = readFileSync(path, 'utf8').split(/\r?\n/);
  let cur = null;
  let inBitmap = false;
  for (const line of lines) {
    if (line.startsWith('FONT_ASCENT ')) meta.ascent = Number(line.split(' ')[1]);
    else if (line.startsWith('FONT_DESCENT ')) meta.descent = Number(line.split(' ')[1]);
    else if (line.startsWith('ENCODING ')) cur = { cp: Number(line.split(' ')[1]), rows: [] };
    else if (line.startsWith('DWIDTH ') && cur) cur.adv = Number(line.split(' ')[1]);
    else if (line.startsWith('BBX ') && cur) [cur.w, cur.h, cur.x, cur.y] = line.split(' ').slice(1).map(Number);
    else if (line === 'BITMAP') inBitmap = true;
    else if (line === 'ENDCHAR') {
      if (cur && cur.cp >= 0) glyphs.set(cur.cp, cur);
      cur = null;
      inBitmap = false;
    } else if (inBitmap && cur) cur.rows.push(parseInt(line, 16));
  }
  return { glyphs, meta };
}

const zh = parseBdf(zhPath);
const latin = latinPath ? parseBdf(latinPath) : null;

const want = new Set();
for (let c = 0x20; c < 0x7f; c += 1) want.add(c);
const gb = new TextDecoder('gb18030');
for (let hi = 0xb0; hi <= 0xd7; hi += 1) {
  for (let lo = 0xa1; lo <= 0xfe; lo += 1) {
    if (hi === 0xd7 && lo > 0xf9) break;
    const ch = gb.decode(new Uint8Array([hi, lo]));
    want.add(ch.codePointAt(0));
  }
}
for (const ch of '，。、：；！？「」『』（）《》—…·￥％＋－×÷→←↑↓≈≥≤～') want.add(ch.codePointAt(0));
for (const ch of readFileSync(join(ROOT, 'sidecars/agy-lens/web/i18n.js'), 'utf8')) {
  const cp = ch.codePointAt(0);
  if (cp >= 0x20) want.add(cp);
}

// Pack: per glyph [cp(3 bytes) adv w h x+8 y+8] + row bytes (ceil(w/8) per row).
const bytes = [];
let count = 0;
const missing = [];
for (const cp of [...want].sort((a, b) => a - b)) {
  const g = (cp < 0x2e80 && latin && latin.glyphs.get(cp)) || zh.glyphs.get(cp) || (latin && latin.glyphs.get(cp));
  if (!g) {
    if (cp >= 0x2e80 || (cp > 0x20 && cp < 0x7f)) missing.push(String.fromCodePoint(cp));
    continue;
  }
  const rb = Math.ceil(g.w / 8) || 0;
  bytes.push((cp >> 16) & 255, (cp >> 8) & 255, cp & 255, g.adv, g.w, g.h, g.x + 8, g.y + 8);
  for (const row of g.rows) {
    const bits = g.w ? row >> ((Math.ceil(g.w / 8) * 8 - rb * 8)) : 0;
    for (let i = rb - 1; i >= 0; i -= 1) bytes.push((row >> (i * 8)) & 255);
    void bits;
  }
  count += 1;
}
const b64 = Buffer.from(bytes).toString('base64');
const out = `// Generated by scripts/share-art/build-font.mjs. Do not edit.
// Fusion Pixel Font 12px (proportional), Copyright (c) 2022 TakWolf (https://takwolf.com),
// licensed under the SIL Open Font License 1.1: sidecars/agy-lens/share-art/fonts/OFL.txt.
// ${count} glyphs: printable ASCII, GB2312 level-1 hanzi, CJK punctuation and every i18n character.
export const PIXEL_FONT_ASCENT = ${zh.meta.ascent};
export const PIXEL_FONT_DESCENT = ${zh.meta.descent};
export const PIXEL_FONT_DATA = '${b64}';
`;
writeFileSync(join(ROOT, 'sidecars/agy-lens/web/views/share-font.js'), out);
const fontDir = join(ROOT, 'sidecars/agy-lens/share-art/fonts');
mkdirSync(fontDir, { recursive: true });
copyFileSync(join(dirname(zhPath), 'OFL.txt'), join(fontDir, 'OFL.txt'));
console.log(`${count} glyphs, ${(b64.length / 1024).toFixed(0)} KB base64; missing: ${missing.join('') || 'none'}`);
