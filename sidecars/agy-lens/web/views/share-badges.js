export const BADGE_SIZE = 24;
const LOCKED = { o: '#1a1c28', light: '#565d78', mid: '#3e4459', dark: '#2c3142' };

/** Colour of one badge pixel, or null when transparent. Locked badges collapse to a grey ramp. */
export function badgePixel(id, x, y, locked = false) {
  const art = BADGE_ART[id];
  if (!art) return null;
  const ch = art.rows[y] ? art.rows[y][x] : '.';
  if (!ch || ch === '.') return null;
  if (locked) {
    if (ch === 'o') return LOCKED.o;
    if ('lApq'.includes(ch)) return LOCKED.light;
    if ('dbkwRG'.includes(ch)) return LOCKED.dark;
    return LOCKED.mid;
  }
  if (ch === 'd') return art.ramp[0];
  if (ch === 'm') return art.ramp[1];
  if (ch === 'l') return art.ramp[2];
  return SHARED[ch] || null;
}
