export function normalizeLang(lang) {
  return lang === 'zh' ? 'zh' : 'en';
}

export function localeFor(lang) {
  return normalizeLang(lang) === 'zh' ? 'zh-CN' : 'en';
}

export function detectDefaultLang(navigatorLanguage, storedLang) {
  if (storedLang === 'en' || storedLang === 'zh') return storedLang;
  if (typeof navigatorLanguage === 'string' && /^zh(?:$|[-_])/i.test(navigatorLanguage.trim())) {
    return 'zh';
  }
  return 'en';
}

export function createTranslator(lang) {
  const norm = normalizeLang(lang);
  const dict = I18N[norm];
  const t = (key, ...args) => {
    const v = Object.hasOwn(dict, key)
      ? dict[key]
      : (Object.hasOwn(I18N.en, key) ? I18N.en[key] : undefined);
    if (typeof v === 'function') return v(...args);
    return v !== undefined ? v : key;
  };
  t.lang = norm;
  t.locale = localeFor(norm);
  return t;
}
